import type { LessonBlock, SeedModule } from '@/lib/content/types';

function quickQuiz(
  id: string,
  text: string,
  options: string[],
  correct: number[],
  explanation: string,
): LessonBlock {
  return {
    type: 'quiz', title: 'Проверьте понимание',
    questions: [{
      id, text,
      options: options.map((option, index) => ({ id: `${id}-${index}`, text: option })),
      correct: correct.map((index) => `${id}-${index}`),
      explanation,
    }],
  };
}

